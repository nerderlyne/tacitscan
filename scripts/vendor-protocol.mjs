// Reproduce the structural decoders from a reviewed local Tacit checkout.
// No upstream runtime, network services, or wallet code is executed.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import ts from '../indexer/node_modules/typescript/lib/typescript.js';

const upstream = process.argv[2] || '../tacit';
const revision = '7a917a8ec4dad72210351d80bcbf269073ac790d';
const head = execFileSync('git', ['-C', upstream, 'rev-parse', 'HEAD'], {encoding:'utf8'}).trim();
if (head!==revision) throw new Error(`Expected ${revision}, got ${head}`);
const source = fs.readFileSync(path.join(upstream, 'worker/src/index.js'), 'utf8');
const tree = ts.createSourceFile('index.js', source, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
const declarations = new Map();
for (const node of tree.statements) {
  if (ts.isFunctionDeclaration(node) && node.name) declarations.set(node.name.text, node.getText(tree));
  if (ts.isVariableStatement(node)) for (const d of node.declarationList.declarations) {
    if (ts.isIdentifier(d.name)) declarations.set(d.name.text, 'const ' + d.getText(tree) + ';');
  }
}
const roots = ['decodeTLpAddPayload','decodeTLpRemovePayload','decodeTSwapBatchPayload',
  'decodeTProtocolFeeClaimPayload','decodeTSwapVarPayload','decodeTSwapRoutePayload',
  'decodeTFarmInitPayload','decodeTLpBondPayload','decodeTLpUnbondPayload',
  'decodeTLpHarvestPayload','decodeTFarmRefundPayload','decodePreauthBidPayload','decodePreauthBidVarPayload'];
const selected = new Map();
const shimmed = new Set(['bytesToHex', 'compressedPointFromHex']);
function include(name) {
  if (selected.has(name) || shimmed.has(name)) return;
  const text = declarations.get(name);
  if (!text) throw new Error(`Missing declaration ${name}`);
  selected.set(name, text);
  const ast = ts.createSourceFile('fragment.js', text, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
  function walk(n) {
    if (ts.isIdentifier(n) && declarations.has(n.text) && !shimmed.has(n.text)) {
      // Only helpers referenced by these pure structural decoders.
      if (n.text !== name) include(n.text);
    }
    ts.forEachChild(n, walk);
  }
  walk(ast);
}
roots.forEach(include);
if (selected.size > 65) throw new Error('Unexpected dependency expansion; review extraction');
const preamble = `// @ts-nocheck\n// Generated by scripts/vendor-protocol.mjs from Tacit ${head}.\n// Structural decoding only. Original MIT license in LICENSE.tacit.\nimport { secp256k1 } from '@noble/curves/secp256k1';\nconst bytesToHex = (b) => Buffer.from(b).toString('hex');\nconst compressedPointFromHex = (h) => secp256k1.ProjectivePoint.fromHex(h);\n`;
fs.mkdirSync('indexer/src/vendor', {recursive:true});
fs.writeFileSync('indexer/src/vendor/bitcoin-decoders.ts', preamble + [...selected.values()].join('\n\n') + '\nexport { ' + roots.join(', ') + ' };\n');
fs.copyFileSync(path.join(upstream, 'LICENSE'), 'indexer/src/vendor/LICENSE.tacit');
fs.writeFileSync('indexer/src/vendor/provenance.json', JSON.stringify({revision:head, source:'worker/src/index.js', sha256:createHash('sha256').update(source).digest('hex'), declarations:[...selected.keys()]}, null, 2)+'\n');
console.log(`Vendored ${roots.length} decoders, ${selected.size} declarations`);
